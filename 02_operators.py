# Algunos operadores aritmeticos

# Numeros
print(3 + 4) # Suma
print(3 - 4) # Resta
print(3 * 4) # Multiplicacion
print(3 / 4) # Division
print(10 % 2) # Modulo
print(10 // 2) # Division entera
print(10 ** 2) # Calcular exponente

# Cadenas
# Con cadenas solo se  puede usar el operador de suma para concatenar
print('Hola!'+'soy tu archivo py')
print('Hola!'+  str(4))
print('Hola!'*4) # Repetir la cadena 4 veces

# Algunos operadores comparativos

print(2 > 4) # Mayor que
print(2 < 5) # Menor que
print(2 <= 6) # Menor o igualdad
print(2 >= 21) # Mayor o igualdad
print(2 == 3) # Igualdad
print(2 != 3) # Diferencia
